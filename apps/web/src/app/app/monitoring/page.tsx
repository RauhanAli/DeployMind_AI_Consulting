"use client";

import { useQuery } from "@tanstack/react-query";
import { Activity, AlertTriangle, CheckCircle2, Clock, Coins, Gauge, HeartPulse, Search } from "lucide-react";
import { useEffect, useState } from "react";

import { PageHeader, QueryView, StatCard } from "@/components/app/common";
import { HBar, TimeSeries } from "@/components/domain/charts";
import { Badge, Card, CardContent, CardHeader, CardTitle, Select, Table, Td, Th } from "@/components/ui";
import { api, streamEvents } from "@/lib/api";
import { compact, pct, usd } from "@/lib/utils";

export default function Monitoring() {
  const [hours, setHours] = useState(24);
  const [source, setSource] = useState<"real" | "demo" | "all">("real");
  const [app, setApp] = useState("");
  const [live, setLive] = useState<any | null>(null);
  const apps = useQuery({ queryKey: ["apps"], queryFn: () => api<any[]>("/apps") });
  const q = useQuery({ queryKey: ["monitoring", hours, source, app], queryFn: () => api(`/monitoring/overview?hours=${hours}&source=${source}${app ? `&app_id=${app}` : ""}`), refetchInterval: 15000 });
  useEffect(() => {
    setLive(null);
    return streamEvents(`/monitoring/stream?source=${source}${app ? `&app_id=${app}` : ""}`, (e, d) => e === "overview" && setLive(d));
  }, [source, app]);

  return (
    <>
      <PageHeader title="Monitoring" description="Request volume, latency percentiles, tokens, estimated cost, retrieval quality and uptime."
        actions={<>
          <Select aria-label="Application" value={app} onChange={(e) => setApp(e.target.value)} className="w-56"><option value="">All applications</option>{(apps.data ?? []).map((a) => <option key={a.id} value={a.id}>{a.name}</option>)}</Select>
          <Select aria-label="Time window" value={hours} onChange={(e) => setHours(Number(e.target.value))} className="w-36">{[[1, "Last hour"], [24, "Last 24h"], [168, "Last 7 days"], [336, "Last 14 days"]].map(([v, l]) => <option key={v} value={v}>{l}</option>)}</Select>
          <Select aria-label="Telemetry source" value={source} onChange={(e) => setSource(e.target.value as any)} className="w-48"><option value="real">Real telemetry</option><option value="demo">Demo telemetry (seeded)</option><option value="all">All sources</option></Select>
        </>} />
      <div className={source === "real" ? "mb-4 rounded-lg border border-success/30 bg-success/10 p-3 text-sm" : "mb-4 rounded-lg border border-warning/40 bg-warning/10 p-3 text-sm"}>
        {source === "real" ? <>Showing <strong>real telemetry</strong> recorded by the platform API and deployed containers. Seeded demo traffic is excluded.</> :
          <>Includes <strong>synthetic demo telemetry</strong> generated by the seed script to illustrate a production workload. It is not real traffic.</>}
      </div>
      <QueryView q={q} rows={6}>
        {(m: any) => (
          <div className="space-y-6">
            <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
              <StatCard label="Requests" value={compact(m.requests)} hint={`${m.successful} ok · ${m.failed} failed`} icon={Activity} />
              <StatCard label="Error rate" value={pct(m.error_rate, 1)} icon={m.error_rate > 0.05 ? AlertTriangle : CheckCircle2} tone={m.error_rate > 0.05 ? "danger" : "success"} />
              <StatCard label="Latency P50 / P95 / P99" value={`${m.latency_ms.p50} / ${m.latency_ms.p95} / ${m.latency_ms.p99}`} hint="milliseconds" icon={Clock} />
              <StatCard label="Uptime (health checks)" value={m.uptime.ratio === null ? "—" : pct(m.uptime.ratio, 2)} hint={`${m.uptime.successful}/${m.uptime.checks} checks`} icon={HeartPulse} />
              <StatCard label="Tokens" value={compact(m.tokens.total)} hint={`${compact(m.tokens.input)} in · ${compact(m.tokens.output)} out`} icon={Gauge} />
              <StatCard label="Estimated AI cost" value={usd(m.estimated_cost_usd)} hint="From configurable pricing" icon={Coins} />
              <StatCard label="Retrieval latency" value={`${m.retrieval.avg_ms} ms`} hint={`${m.retrieval.avg_chunks} chunks avg`} icon={Search} />
              <StatCard label="Avg top relevance" value={m.retrieval.avg_top_relevance} hint="Hybrid relevance of best chunk" icon={Search} />
            </div>
            {live && (
              <Card><CardContent className="flex flex-wrap items-center gap-4 p-4 text-sm"><Badge tone="primary">● Live · last hour</Badge>
                <span>{live.requests} requests</span><span>{pct(live.error_rate, 1)} errors</span><span>P95 {live.latency_ms.p95} ms</span><span>{usd(live.estimated_cost_usd)}</span></CardContent></Card>
            )}
            <div className="grid gap-4 xl:grid-cols-2">
              <TimeSeries title="Request volume" data={m.series} series={[{ key: "requests", label: "Requests" }, { key: "errors", label: "Errors" }]} kind="bar" />
              <TimeSeries title="P95 latency (ms)" data={m.series} series={[{ key: "p95_ms", label: "P95 ms" }]} />
              <TimeSeries title="Tokens" data={m.series} series={[{ key: "tokens", label: "Tokens" }]} kind="area" />
              <TimeSeries title="Estimated cost (USD)" data={m.series} series={[{ key: "cost_usd", label: "Cost" }]} kind="area" format={(v) => `$${v.toFixed(3)}`} />
            </div>
            <div className="grid gap-4 xl:grid-cols-2">
              <HBar title="Requests by model" data={m.models.map((x: any) => ({ ...x, label: `${x.provider}:${x.model}` }))} valueKey="requests" labelKey="label" />
              <Card><CardHeader><CardTitle className="text-sm">Model usage</CardTitle></CardHeader><CardContent>
                <Table><thead><tr><Th>Model</Th><Th>Requests</Th><Th>Tokens</Th><Th>Cost</Th></tr></thead><tbody>
                  {m.models.map((x: any) => <tr key={x.provider + x.model}><Td className="font-mono text-xs">{x.provider}:{x.model}</Td><Td>{x.requests}</Td><Td>{compact(x.tokens)}</Td><Td>{usd(x.cost_usd)}</Td></tr>)}
                </tbody></Table>
                <p className="mt-2 text-xs text-muted-foreground">Sources in window: {Object.entries(m.sources_present).map(([k, v]) => `${k} (${v})`).join(", ") || "none"}</p>
              </CardContent></Card>
            </div>
          </div>
        )}
      </QueryView>
    </>
  );
}
